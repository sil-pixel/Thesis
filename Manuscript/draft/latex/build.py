'''
Assemble the Markdown section files into one LaTeX file with the Springer Nature template (BMC Psychiatry
submission), and compile it.
The Markdown files in Manuscript/draft/ are the source; manuscript.tex is regenerated on every run, so edit the
Markdown, not the .tex.

Usage (from any folder):
    python3 build.py            # keeps the <!-- src --> comments as % comments in manuscript.tex
    python3 build.py --clean    # drops them (for the file sent to the journal)
    python3 build.py --no-pdf   # writes manuscript.tex only
    python3 build.py --no-figures   # leaves out the figure pages (the journal takes figures as separate files)

Requires pandoc and a TeX installation (pdflatex, bibtex, latexmk).
The template asks for one .tex file without \\input, so everything is written into manuscript.tex.
'''

import re
import shutil
import subprocess
import sys
from pathlib import Path

LATEX_DIR = Path(__file__).resolve().parent
DRAFT_DIR = LATEX_DIR.parent
TEMPLATE_DIR = DRAFT_DIR.parent / "sn-article-template"
OUT_TEX = LATEX_DIR / "manuscript.tex"

BODY_FILES = ["02_background.md", "03_methods.md", "04_results.md", "05_discussion.md"]
BACKMATTER_FILE = "06_backmatter.md"
TITLE_FILE = "01_title_abstract.md"
# Figure pages appended after the references for reviewers of the draft (made by figures/make_figures.py)
FIGURES = ["fig1_flow.pdf", "fig2_architecture.pdf", "fig3_calibration.pdf", "fig4_attribution.pdf"]

PREAMBLE = r'''%% Generated by build.py from the Markdown files in Manuscript/draft/ -- do not edit by hand.
%% Springer Nature LaTeX template v3.1 (sn-jnl.cls), Vancouver numbered references, for BMC Psychiatry.
\documentclass[pdflatex,sn-vancouver-num]{sn-jnl}

\usepackage{graphicx}%
\usepackage{multirow}%
\usepackage{amsmath,amssymb,amsfonts}%
\usepackage{amsthm}%
\usepackage{mathrsfs}%
\usepackage[title]{appendix}%
\usepackage{xcolor}%
\usepackage{textcomp}%
\usepackage{manyfoot}%
\usepackage{booktabs}%
\usepackage{longtable,array,calc}% tables written by pandoc
\usepackage{url}%
\providecommand{\tightlist}{\setlength{\itemsep}{0pt}\setlength{\parskip}{0pt}}
\makeatletter\providecommand{\real}[1]{#1}\makeatother
%UNICODE%

\raggedbottom

\begin{document}
'''

# Characters that pdflatex does not know by default
UNICODE_MAP = {
    "²": r"\textsuperscript{2}", "⁻": r"\textsuperscript{--}", "⁴": r"\textsuperscript{4}",
    "⁵": r"\textsuperscript{5}", "⁶": r"\textsuperscript{6}", "¹": r"\textsuperscript{1}",
    "×": r"\ensuremath{\times}", "−": r"\ensuremath{-}", "≥": r"\ensuremath{\geq}", "≤": r"\ensuremath{\leq}",
    "→": r"\ensuremath{\rightarrow}", "Δ": r"\ensuremath{\Delta}", "ρ": r"\ensuremath{\rho}",
    "δ": r"\ensuremath{\delta}", "γ": r"\ensuremath{\gamma}", "β": r"\ensuremath{\beta}",
    "≈": r"\ensuremath{\approx}", "±": r"\ensuremath{\pm}", "–": "--", "—": "---", "’": "'", "‘": "`",
    "“": "``", "”": "''", "…": r"\ldots{}", "ö": r"\"o", "ä": r"\"a", "å": r"\aa{}", "é": r"\'e",
    "ñ": r"\~n", "Ö": r"\"O", "Ä": r"\"A", "Å": r"\AA{}", "·": r"\ensuremath{\cdot}", "✅": "[ok]",
    "⚠": "[!]", "§": r"\S{}", "❌": "[x]", "≠": r"\ensuremath{\neq}", "µ": r"\ensuremath{\mu}", "σ": r"\ensuremath{\sigma}",
}


def pandoc(markdown, backmatter=False, clean=False):
    cmd = ["pandoc", "-f", "markdown+tex_math_dollars-raw_tex-auto_identifiers", "-t", "latex", "--natbib", "--wrap=preserve",
           "--lua-filter", str(LATEX_DIR / "md2sn.lua")]
    if backmatter:
        cmd += ["-M", "backmatter=true"]
    if clean:
        cmd += ["-M", "strip_comments=true"]
    result = subprocess.run(cmd, input=markdown, capture_output=True, text=True, check=True)
    return result.stdout


def unicode_declarations(text):
    used = sorted({ch for ch in text if ord(ch) > 127})
    unknown = [ch for ch in used if ch not in UNICODE_MAP]
    if unknown:
        sys.exit(f"Add these characters to UNICODE_MAP in build.py: {' '.join(unknown)}")
    return "\n".join(
        f"\\DeclareUnicodeCharacter{{{ord(ch):04X}}}{{{UNICODE_MAP[ch]}}}" for ch in used
    )


def section_text(markdown, heading):
    '''Text under "## heading" up to the next "## " heading, without comments.'''
    match = re.search(rf"^## {re.escape(heading)}\s*\n(.*?)(?=^## |\Z)", markdown, flags=re.S | re.M)
    if not match:
        sys.exit(f"Section '## {heading}' not found in {TITLE_FILE}")
    return match.group(1).strip()


def front_matter(clean):
    text = (DRAFT_DIR / TITLE_FILE).read_text(encoding="utf-8")
    no_comments = re.sub(r"<!--.*?-->", "", text, flags=re.S)

    title = section_text(no_comments, "Title").splitlines()[0].strip()
    abstract_md = section_text(text, "Abstract")
    keywords = section_text(no_comments, "Keywords").splitlines()[0].strip()

    abstract_tex = pandoc(abstract_md, clean=clean).strip()
    keywords_tex = ", ".join(k.strip() for k in keywords.split(";"))

    return (
        f"\\title[Deep fusion vs mixed models for adolescent psychopathology]{{{title}}}\n\n"
        f"% Authors: replace with \\author[1]{{\\fnm{{First}} \\sur{{Last}}}}\\email{{...}} and \\affil[1]{{...}}\n"
        f"\\author*[1]{{\\fnm{{\\textcolor{{red}}{{[AUTHOR INPUT: authors and affiliations]}}}}}}\\email{{[AUTHOR INPUT]}}\n"
        f"\\affil*[1]{{\\orgname{{\\textcolor{{red}}{{[AUTHOR INPUT: affiliation]}}}}}}\n\n"
        f"\\abstract{{{abstract_tex}}}\n\n"
        f"\\keywords{{{keywords_tex}}}\n\n"
        "\\maketitle\n"
    )


def figure_pages():
    pages = ["\n%% ---------------- figures (review copy only) ----------------\n"]
    for number, name in enumerate(FIGURES, start=1):
        pages.append("\\clearpage\n\\noindent\\textbf{Fig. %d}\\par\\medskip\n"
                     "\\noindent\\includegraphics[width=\\textwidth,height=0.85\\textheight,keepaspectratio]"
                     "{../figures/%s}\n" % (number, name))
    return "".join(pages)


def main():
    clean = "--clean" in sys.argv
    parts = [front_matter(clean)]
    for name in BODY_FILES:
        parts.append(f"%% ---------------- {name} ----------------\n")
        parts.append(pandoc((DRAFT_DIR / name).read_text(encoding="utf-8"), clean=clean))
    parts.append("\\backmatter\n")
    parts.append(f"%% ---------------- {BACKMATTER_FILE} ----------------\n")
    parts.append(pandoc((DRAFT_DIR / BACKMATTER_FILE).read_text(encoding="utf-8"), backmatter=True, clean=clean))
    parts.append("\n\\bibliography{references}\n")
    if "--no-figures" not in sys.argv:
        parts.append(figure_pages())
    parts.append("\n\\end{document}\n")

    body = "".join(parts)
    tex = PREAMBLE.replace("%UNICODE%", unicode_declarations(body)) + body
    OUT_TEX.write_text(tex, encoding="utf-8")
    print(f"Written: {OUT_TEX}")

    # The class and the reference style come from the template folder in Manuscript/
    for source in [TEMPLATE_DIR / "sn-jnl.cls", TEMPLATE_DIR / "bst" / "sn-vancouver-num.bst"]:
        shutil.copy(source, LATEX_DIR / source.name)

    if "--no-pdf" not in sys.argv:
        subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", OUT_TEX.name],
                       cwd=LATEX_DIR, check=True)
        print(f"Compiled: {LATEX_DIR / 'manuscript.pdf'}")


if __name__ == "__main__":
    main()
